const $ = (sel, root = document) => root.querySelector(sel);
const $$ = (sel, root = document) => [...root.querySelectorAll(sel)];

function banner(el, msg, kind = 'err') {
  el.innerHTML = msg ? `<div class="banner ${kind}">${esc(msg)}</div>` : '';
}

/** Warn once, on every page, if the backend is the mock rather than the real thing. */
async function checkHealth(slot) {
  try {
    const h = await apiGet('/api/health');
    if (h.mock) {
      slot.innerHTML = `<div class="banner">Mock backend — every number on this page is fake,
        generated by <span class="mono">web/ui/mock_api.py</span> from the answer keys. Start
        <span class="mono">web.app</span> for real runs.</div>`;
    } else if (h.mode === 'test') {
      slot.innerHTML = `<div class="banner">Backend is in <b>test</b> mode: runs go through the Claude Code
        login and are excluded from the eval table. Use <span class="mono">AUDITOR_MODE=prod</span> for
        anything that goes in the report.</div>`;
    }
    return h;
  } catch (e) {
    banner(slot, e.message, 'err');
    return null;
  }
}
